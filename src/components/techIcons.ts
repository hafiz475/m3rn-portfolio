/** Relative luminance of a 6-digit hex colour, 0 (black) to 1 (white). */
const luminance = (hex: string) => {
  const [r, g, b] = [0, 2, 4].map((i) => {
    const c = parseInt(hex.slice(i, i + 2), 16) / 255;
    return c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4;
  });
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
};

export interface TechIconData {
  path: string;
  /** Brand colour, swapped for a light grey when the brand colour would vanish on the dark site */
  color: string;
}

export const getTechIcon = (name: string): TechIconData | null => {
  // "React 18" and "Next.js 16" share their unversioned icon
  const icon = ICONS[name] ?? ICONS[name.replace(/\s+\d+(\.\d+)*$/, '')];
  if (!icon) return null;
  return { path: icon.path, color: luminance(icon.hex) < 0.12 ? '#E6E8EB' : `#${icon.hex}` };
};
